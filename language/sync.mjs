#!/usr/bin/env node
/*
  sync.mjs - puts the newest language pack into a Mappy widget folder, no git needed.

    node sync.mjs "C:\arcgis-experience-builder-1.21\client\your-extensions\widgets\mappy"

  Downloads language-pack.json from the repository (or reads it from this folder when you
  cloned the repo), checks it, and rewrites src/brain/languagePack.ts in that widget folder
  when the pack is newer than the one there. Rebuild (or restart pnpm start) afterwards.
  Settings > Language > "Get language updates" does the same thing per app, with no rebuild.
*/
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = process.env.MAPPY_LANGUAGE_REPO || 'brianmcleer/mappy-widget'
const URL = `https://raw.githubusercontent.com/${REPO}/HEAD/language/language-pack.json`
const here = path.dirname(fileURLToPath(import.meta.url))

const target = path.resolve(process.argv[2] || '.')
const file = path.join(target, 'src', 'brain', 'languagePack.ts')
if (!fs.existsSync(path.join(target, 'manifest.json')) || !fs.existsSync(file)) {
  console.error(`Not a Mappy widget folder (no manifest.json and src/brain/languagePack.ts): ${target}`)
  process.exit(1)
}

let pack = null
const local = path.join(here, 'language-pack.json')
if (!process.argv.includes('--download') && fs.existsSync(local)) pack = JSON.parse(fs.readFileSync(local, 'utf8'))
if (!pack) {
  const r = await fetch(URL)
  if (!r.ok) { console.error(`Download failed (${r.status}): ${URL}`); process.exit(1) }
  pack = await r.json()
}
if (!pack || pack.format !== 1 || !/^\d{4}\.\d{2}\.\d{2}(\.\d+)?$/.test(pack.version || '')) { console.error('That is not a Mappy language pack.'); process.exit(1) }
// Only the pack's known fields, with their expected shapes, reach the generated file.
const str = (v) => typeof v === 'string' ? v : ''
const strs = (v) => Array.isArray(v) ? v.filter(x => typeof x === 'string') : []
pack = {
  format: 1,
  version: str(pack.version),
  synonyms: Array.isArray(pack.synonyms) ? pack.synonyms.map(strs).filter(g => g.length > 1) : [],
  rewrites: Array.isArray(pack.rewrites) ? pack.rewrites.filter(r => Array.isArray(r) && r.length === 2 && r.every(x => typeof x === 'string')) : [],
  fixes: Object.fromEntries(Object.entries(pack.fixes || {}).filter(([k, v]) => typeof k === 'string' && typeof v === 'string')),
  words: str(pack.words),
  known: pack.known && typeof pack.known === 'object' ? { m: Number(pack.known.m) || 0, k: Number(pack.known.k) || 0, n: Number(pack.known.n) || 0, b64: str(pack.known.b64) } : undefined,
  stats: pack.stats && typeof pack.stats === 'object' ? Object.fromEntries(Object.entries(pack.stats).filter(([, v]) => typeof v === 'number')) : undefined
}

const have = (fs.readFileSync(file, 'utf8').match(/"version":"([^"]+)"|version: '([^']+)'/) || []).slice(1).find(Boolean) || '0000.00.00'
const newer = (a, b) => { const x = a.split('.').map(Number); const y = b.split('.').map(Number); for (let i = 0; i < Math.max(x.length, y.length); i++) { if ((x[i] || 0) !== (y[i] || 0)) return (x[i] || 0) > (y[i] || 0) } return false }
if (!newer(pack.version, have)) { console.log(`Language pack ${have} is already the newest.`); process.exit(0) }
fs.writeFileSync(file, `/* Generated by language/build.mjs from Open English WordNet (CC BY 4.0) and reported phrases.
   Do not edit by hand: change language/seed.json or language/learned.json in the repository. */
const PACK: any = ${JSON.stringify(pack)}
export default PACK
`)
console.log(`Language pack ${have} -> ${pack.version} (${pack.stats?.understood ?? '?'} of ${pack.stats?.phrases ?? '?'} test phrases). Rebuild the widget to use it.`)
